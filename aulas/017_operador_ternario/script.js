//  os operadores ternários são uma forma de escrever um if/else mais compacto //
//  a sintaxe é a seguinte: //
//  condição ? expressão_verdadeira : expressão_falsa //
//  ou seja, se a condição for verdadeira, executa a expressão_verdadeira, senão executa a expressão_falsa //

let idade = 18;
let status = idade >= 18 ? "maior de idade" : "menor de idade";
console.log(status); // maior de idade