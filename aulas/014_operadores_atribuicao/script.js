// operadores de atribuicao:  =, +=, -=, *=, /=, %= 

let num = 10;

num += 2; // num = num + 2; 
console.table(num);

num -= 2; // num = num - 2; subtração
console.table(num);

num *= 2; // num = num * 2; multiplicação
console.table(num);

num /= 2; // num = num / 2; divisão
console.table(num);

num %= 2; // num = num % 2; resto da divisão
console.table(num);

num **= 2; // num = num ** 2; exponencial
console.table(num);

