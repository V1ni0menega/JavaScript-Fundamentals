//Concatenação de strings

let nome = 'Carlos';
let sobrenome = 'Andrade';

console.log(nome);
console.log(sobrenome);

// operador de concatenação
let nome_completo = nome + ' ' + sobrenome;
console.log(nome_completo);

// operador de atribuição com concatenação
nome += ' ' + sobrenome;
console.log(nome);

